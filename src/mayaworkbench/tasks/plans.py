"""Implementation planning.

A plan is a persisted, reviewable artifact, not hidden chain-of-thought. It is
generated by the Technical Planner role (or supplied by the user as JSON for
offline operation), validated against the contract's path scope, and bound into
the write approval by hash. The Implementer may deviate, but the approval and
audit trail keep the approved plan visible.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from pydantic import ValidationError as PydanticValidationError

from mayaworkbench.config import Settings
from mayaworkbench.domain.enums import (
    ActorKind,
    ArtifactKind,
    EventType,
    WorkflowState,
)
from mayaworkbench.domain.models import (
    RepositorySnapshot,
    Task,
    TaskContract,
    TaskPlan,
    WorkflowEvent,
    WorkflowRun,
)
from mayaworkbench.errors import PolicyError, TaskError
from mayaworkbench.ids import new_ulid
from mayaworkbench.models.base import ChatMessage, ModelRequest
from mayaworkbench.models.gateway import ModelGateway
from mayaworkbench.storage.artifacts import ArtifactStore
from mayaworkbench.storage.stores import (
    EventStore,
    FileStore,
    PlanStore,
    RunStore,
)
from mayaworkbench.tasks.agent_models import PlanPayload
from mayaworkbench.tasks.approvals import canonical_sha256
from mayaworkbench.workspace.policy import PathPolicy, PolicyViolation

PLANNER_PROMPT = """You are the Technical Planner role in MayaWorkbench.

Produce the smallest implementation plan that satisfies the task contract,
without touching excluded paths or inventing repository facts. You have a
pinned file inventory only: you have not read the files yet, so describe what
to inspect rather than assuming implementation details.

The plan must:
- stay inside the contract's allowed paths;
- list concrete steps, files to inspect or change, and deterministic checks;
- prefer existing project conventions and targeted tests;
- state risks and unknowns honestly;
- not include commands that install dependencies or use the network.

Return only the structured PlanPayload JSON. Do not claim tests have run.
"""


class PlanService:
    def __init__(
        self,
        *,
        settings: Settings,
        gateway: ModelGateway,
        plans: PlanStore,
        runs: RunStore,
        files: FileStore,
        artifacts: ArtifactStore,
        events: EventStore,
    ):
        self.settings = settings
        self.gateway = gateway
        self.plans = plans
        self.runs = runs
        self.files = files
        self.artifacts = artifacts
        self.events = events

    def create(
        self,
        *,
        run: WorkflowRun,
        task: Task,
        contract: TaskContract,
        snapshot: RepositorySnapshot,
        plan_file: str | Path | None = None,
    ) -> TaskPlan:
        if run.state != WorkflowState.PLANNING:
            raise TaskError(f"Run is {run.state.value}; planning requires PLANNING")
        if plan_file is not None:
            payload = self._load_file(plan_file)
            invocation_id = None
        else:
            payload, invocation_id = self._generate(run=run, task=task, contract=contract)
        self._validate_paths(payload, contract)
        version = self.plans.next_version(run.id)
        plan_hash = canonical_sha256(payload.model_dump(mode="json"))
        artifact = self.artifacts.put_text(
            json.dumps(payload.model_dump(mode="json"), indent=2, sort_keys=True),
            kind=ArtifactKind.IMPLEMENTATION_PLAN,
            media_type="application/json",
            created_by="planner",
        )
        plan = TaskPlan(
            id="plan_" + new_ulid(),
            task_id=task.id,
            run_id=run.id,
            project_id=run.project_id,
            version=version,
            summary=payload.summary,
            steps=payload.steps,
            files=payload.files,
            checks=payload.checks,
            risks=payload.risks,
            unknowns=payload.unknowns,
            estimated_steps=payload.estimated_steps,
            plan_sha256=plan_hash,
            model_invocation_id=invocation_id,
            artifact_id=artifact.id,
        )
        self.plans.create(plan)
        self.runs.update_progress(run.id, plan_id=plan.id)
        self.events.append(
            WorkflowEvent(
                event_id="evt_" + new_ulid(),
                event_type=EventType.PLAN_CREATED,
                project_id=run.project_id,
                snapshot_id=run.snapshot_id,
                task_id=run.task_id,
                run_id=run.id,
                entity_type="plan",
                entity_id=plan.id,
                actor_kind=ActorKind.MODEL if invocation_id else ActorKind.USER,
                actor_name="technical_planner" if invocation_id else "local-user",
                payload={
                    "version": plan.version,
                    "plan_sha256": plan.plan_sha256,
                    "files": plan.files,
                    "estimated_steps": plan.estimated_steps,
                    "model_invocation_id": invocation_id,
                },
            )
        )
        return plan

    # ------------------------------------------------------------------ inputs
    def _load_file(self, plan_file: str | Path) -> PlanPayload:
        path = Path(plan_file).expanduser()
        if not path.is_file():
            raise TaskError(f"Plan file not found: {path}")
        try:
            raw = json.loads(path.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError) as exc:
            raise TaskError(f"Plan file is not valid JSON: {exc}") from exc
        try:
            return PlanPayload.model_validate(raw)
        except PydanticValidationError as exc:
            raise TaskError(f"Plan file does not match the plan schema: {exc}") from exc

    def _generate(
        self, *, run: WorkflowRun, task: Task, contract: TaskContract
    ) -> tuple[PlanPayload, str | None]:
        file_list = self.files.list_by_snapshot(
            contract.snapshot_id, limit=400, include_skipped=False
        )
        inventory = [
            {
                "path": item.path,
                "language": item.language,
                "lines": item.line_count,
                "is_test": item.is_test,
            }
            for item in file_list
        ]
        prompt = {
            "task": {
                "title": task.title,
                "type": task.task_type.value,
                "goal": task.goal,
            },
            "contract": {
                "allowed_paths": contract.scope.allowed_paths,
                "excluded_paths": contract.scope.excluded_paths,
                "acceptance_criteria": contract.acceptance_criteria,
                "unknowns": contract.unknowns,
                "constraints": contract.constraints.model_dump(mode="json"),
            },
            "repository_inventory": inventory,
            "inventory_truncated": len(file_list) >= 400,
        }
        request = ModelRequest(
            purpose="task_plan",
            messages=[
                ChatMessage(role="system", content=PLANNER_PROMPT),
                ChatMessage(
                    role="user",
                    content=(
                        "Plan this task. Context follows as JSON.\n\n"
                        + json.dumps(prompt, ensure_ascii=False, indent=2)
                    ),
                ),
            ],
            json_schema=PlanPayload.model_json_schema(),
            schema_name="PlanPayload",
            max_output_tokens=min(3000, self.settings.model.max_output_tokens),
        )
        response, invocation = self.gateway.structured(
            request,
            project_id=run.project_id,
            snapshot_id=run.snapshot_id,
            purpose="task_plan",
            correlation_id=run.id,
        )
        usage = response.usage
        used = usage.total_tokens
        if used is None and usage.prompt_tokens is not None and usage.completion_tokens is not None:
            used = usage.prompt_tokens + usage.completion_tokens
        if used is not None:
            self.runs.set_flags(run.id, add_tokens=used)
        if usage.cost_usd is not None:
            self.runs.set_flags(run.id, add_cost_usd=usage.cost_usd)
        payload = response.structured
        if payload is None:
            try:
                payload = _extract_json(response.text)
            except ValueError as exc:
                raise TaskError(f"Planner did not return a JSON plan: {exc}") from exc
        try:
            return PlanPayload.model_validate(payload), invocation.id
        except PydanticValidationError as exc:
            raise TaskError(f"Planner output does not match the plan schema: {exc}") from exc

    def _validate_paths(self, payload: PlanPayload, contract: TaskContract) -> None:
        policy = PathPolicy(
            Path("."),
            allowed_paths=contract.scope.allowed_paths,
            excluded_paths=contract.scope.excluded_paths,
            allow_file_deletion=contract.constraints.allow_file_deletion,
        )
        paths = set(payload.files)
        for step in payload.steps:
            paths.update(step.files)
        for raw in paths:
            try:
                policy.check_write(raw)
            except PolicyViolation as exc:
                raise PolicyError(f"Plan references a path outside the scope: {raw}") from exc


def _extract_json(text: str) -> dict[str, Any]:
    candidate = text.strip()
    start = candidate.find("{")
    end = candidate.rfind("}")
    if start == -1 or end <= start:
        raise ValueError("no JSON object in planner response")
    parsed = json.loads(candidate[start : end + 1])
    if not isinstance(parsed, dict):
        raise ValueError("planner response was not an object")
    return parsed


__all__ = ["PlanService", "PLANNER_PROMPT"]
