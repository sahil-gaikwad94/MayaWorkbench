"""Persistent sessions whose processes live inside the task container.

The host runs only the OCI *client*. Every session command is executed with the
OCI exec API inside the task's retained container, so it inherits that
container's mount policy, cgroup limits, dropped capabilities and network
namespace. There is no code path from this backend to a host process, and no
fallback: if the container cannot be started the capability becomes unavailable
with the observed reason, exactly like the rest of the isolated profile.

Termination targets one session only. Every exec'd process carries
``MAYA_SESSION_ID=<id>`` in its environment, and a generated in-container script
signals only processes with that marker, escalating to ``SIGKILL`` after a
bounded grace period. PID 1 and unrelated container processes are never
signalled.

Why the ID exists before the process
------------------------------------
The session id is generated by :class:`~mayaworkbench.workspace.sessions.SessionManager`
*before* spawn so it can be embedded in the exec environment. That is what makes
"stop this session" precise instead of "stop everything in the container".
"""

from __future__ import annotations

import subprocess
import threading
from pathlib import Path
from typing import TYPE_CHECKING

from mayaworkbench.errors import PolicyError
from mayaworkbench.workspace.runner import CommandPolicy
from mayaworkbench.workspace.sessions import (
    SessionCapability,
    SessionCommand,
    env_digest,
    kill_process_group,
)

if TYPE_CHECKING:  # pragma: no cover - typing only
    from mayaworkbench.workspace.backends import RootlessContainerBackend, RuntimeRef

#: Minimal environment for the host-side OCI client process. The container's
#: environment is set by the backend's exec flags and never inherits this one.
_CLIENT_PATH = "/usr/local/bin:/usr/bin:/bin"


class ContainerSessionBackend:
    """Session processes owned by the task container, not by the host."""

    kind = "container-exec"

    def __init__(
        self,
        backend: "RootlessContainerBackend",
        runtime: "RuntimeRef",
        *,
        workspace: Path,
        policy: CommandPolicy,
    ):
        self.backend = backend
        self.runtime = runtime
        self.workspace = Path(workspace).resolve()
        self.policy = policy
        self._started = False
        self._lock = threading.Lock()
        self._capability = SessionCapability(
            True,
            "session processes run inside the task container through the OCI exec "
            "API; the host runs only the client, never the command",
            self.kind,
        )

    @property
    def capability(self) -> SessionCapability:
        return self._capability

    # ------------------------------------------------------------------ build
    def build(
        self,
        argv: list[str],
        *,
        timeout_seconds: int,
        use_pty: bool,
        session_id: str,
    ) -> SessionCommand:
        self._validate(argv)
        if use_pty:
            # A container-side TTY cannot be verified from this environment, and
            # silently pretending would let a caller believe it has one.
            raise PolicyError(
                "PTY sessions are not available inside the task container",
                hint="Use a non-PTY session, or run an interactive command with "
                "`run_command` instead.",
            )
        self._ensure_container()
        client_argv = self.backend.session_exec_argv(
            self.runtime, list(argv), session_id=session_id
        )
        env = {
            "PATH": _CLIENT_PATH,
            "HOME": str(self.workspace),
            "LANG": "C.UTF-8",
            "LC_ALL": "C.UTF-8",
        }
        return SessionCommand(
            argv=client_argv,
            display_argv=list(argv),
            cwd=self.workspace,
            env=env,
            use_pty=False,
            env_sha256=env_digest(env),
            session_id=session_id,
            timeout_seconds=timeout_seconds,
        )

    def _validate(self, argv: list[str]) -> None:
        """Bound the container-side argv. It is never a shell string."""

        if not argv:
            raise PolicyError("a session command must not be empty")
        if len(argv) > 128:
            raise PolicyError("a session command has too many arguments")
        total = 0
        for item in argv:
            if not isinstance(item, str) or not item:
                raise PolicyError("session arguments must be non-empty strings")
            if "\x00" in item:
                raise PolicyError("session arguments must not contain NUL bytes")
            if "\n" in item and not self.policy.allow_multiline_args:
                raise PolicyError("session arguments must not contain newlines")
            if len(item) > self.policy.max_arg_length:
                raise PolicyError("a session argument exceeds the maximum length")
            total += len(item)
        if total > self.policy.max_total_arg_bytes:
            raise PolicyError("session arguments exceed the maximum total size")

    # -------------------------------------------------------------- container
    def _ensure_container(self) -> None:
        with self._lock:
            if self._started:
                if not self.backend.session_container_running(self.runtime):
                    reason = "the task session container is no longer running"
                    self._capability = SessionCapability(False, reason, "unavailable")
                    raise PolicyError(reason)
                return
            try:
                self.backend.start_session_container(self.runtime)
            except Exception as exc:  # noqa: BLE001 - any failure means unavailable
                reason = f"the task session container could not be started: {exc}"
                self._capability = SessionCapability(False, reason, "unavailable")
                raise PolicyError(reason) from exc
            self._started = True

    # ------------------------------------------------------------- process ops
    def spawn(self, command: SessionCommand) -> tuple[subprocess.Popen, int | None]:
        # The client is started in the runtime root, not in the candidate tree:
        # a client that writes a log or cache file must not pollute the diff.
        client_cwd = Path(self.runtime.overlay.parent)
        try:
            process = subprocess.Popen(
                command.argv,
                cwd=str(client_cwd),
                env=command.env,
                shell=False,
                start_new_session=True,
                stdin=subprocess.PIPE,
                stdout=subprocess.PIPE,
                stderr=subprocess.PIPE,
            )
        except OSError as exc:
            raise PolicyError(
                f"the container session client could not be started: {exc}"
            ) from exc
        return process, None

    def terminate(self, process: subprocess.Popen, *, session_id: str) -> None:
        try:
            self.backend.session_kill(self.runtime, session_id=session_id)
        except Exception:  # noqa: BLE001 - the client is killed regardless
            pass
        finally:
            # The client must not outlive the session even if the in-container
            # terminator failed (for example because the container is gone).
            kill_process_group(process.pid)


__all__ = ["ContainerSessionBackend"]
